#!/usr/bin/env python3
"""Retain the former AntNavigate checkpoint panel as an unsubmitted audit record."""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import statistics
from collections import defaultdict
from pathlib import Path

import yaml

from analyze_dynamics_mse_evidence import ROOT, json_lines, load_scalar_events, protocol, write_csv


PAPER_ROOT = ROOT / "iclr2027"
TABLE_NAMES = (
    "dynamics_mse_rescue.tex",
)
VARIANT_ORDER = ("A01", "A05")


def read_csv(path):
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def scientific(value):
    mantissa, exponent = f"{float(value):.2e}".split("e")
    return rf"{mantissa}\!\times\!10^{{{int(exponent)}}}"


def summarize(rows):
    groups = defaultdict(list)
    for row in rows:
        groups[(row["environment"], row["variant"])].append(row)
    summary = []
    for (environment, variant), group in sorted(groups.items()):
        assert sorted(int(row["seed"]) for row in group) == [1000, 1001, 1002]
        successes = [float(row["test_success"]) for row in group]
        summary.append({
            "environment": environment, "variant": variant, "seeds": len(group),
            "test_success_mean_pct": 100 * statistics.mean(successes),
            "test_success_std_pct": 100 * statistics.stdev(successes),
            "zero_success_seeds": sum(value == 0 for value in successes),
            "mse_selected20k_mean": statistics.mean(float(row["mse_selected20k"]) for row in group),
            "mse_selected20k_std": statistics.stdev(float(row["mse_selected20k"]) for row in group),
            "iqe_selected20k_mean": statistics.mean(float(row["sq_dists_selected20k"]) for row in group),
            "iqe_selected20k_std": statistics.stdev(float(row["sq_dists_selected20k"]) for row in group),
            "mse_last10pct": statistics.mean(float(row["mse_last10pct"]) for row in group),
            "sq_dists_last10pct": statistics.mean(float(row["sq_dists_last10pct"]) for row in group),
        })
    return summary


def render_tables(rows, curves=None):
    summary = {(row["environment"], row["variant"]): row for row in summarize(rows)}
    best = {
        key: choose(summary['AntNavigate-v4', variant][key] for variant in VARIANT_ORDER)
        for key, choose in (('iqe_selected20k_mean', min), ('mse_selected20k_mean', min),
                            ('test_success_mean_pct', max))
    }
    lines = [
        r"% Generated by tools/write_nqrl_dynamics_tables.py.",
        r"\begingroup\small",
        r"\noindent\textbf{(c)} Selected-checkpoint evaluation\par\smallskip",
        r"\setlength{\tabcolsep}{0pt}",
        r"\renewcommand{\arraystretch}{1.12}",
        r"\begin{tabular*}{\linewidth}{@{}l@{\extracolsep{\fill}}rrr@{}}",
        r"\toprule",
        r"Dynamics loss & IQE error & Latent prediction MSE & Test success (\%) \\",
        r"\midrule",
    ]
    for variant, loss in zip(VARIANT_ORDER, ("IQE-only", "IQE+MSE")):
        row = summary[("AntNavigate-v4", variant)]
        mse_mean, mse_std = row["mse_selected20k_mean"], row["mse_selected20k_std"]
        exponent = int(f"{mse_mean:.2e}".split("e")[1])
        mse = rf"({mse_mean / 10**exponent:.2f}\pm{mse_std / 10**exponent:.2f})\times10^{{{exponent}}}"
        values = (
            ('iqe_selected20k_mean', f"{row['iqe_selected20k_mean']:.3f}\\pm{row['iqe_selected20k_std']:.3f}"),
            ('mse_selected20k_mean', mse),
            ('test_success_mean_pct', f"{row['test_success_mean_pct']:.1f}\\pm{row['test_success_std_pct']:.1f}"),
        )
        cells = ['$' + (r'\mathbf{' + value + '}' if row[key] == best[key] else value) + '$'
                 for key, value in values]
        lines.append(loss + ' & ' + ' & '.join(cells) + r' \\')
    lines.extend((r"\bottomrule", r"\end{tabular*}", r"\par\endgroup"))
    return {TABLE_NAMES[0]: "\n".join(lines) + "\n"}


def main():
    archive = PAPER_ROOT / 'archive'
    archive.mkdir(exist_ok=True)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--analysis", type=Path, default=ROOT / "analysis/dynamics_mse")
    parser.add_argument("--tables-only", action="store_true",
                        help="Render the checkpoint panel from archived data without rewriting CSVs.")
    args = parser.parse_args()
    if args.tables_only:
        rows = read_csv(PAPER_ROOT / "data/dynamics_mse_runs.csv")
        for name, content in render_tables(rows).items():
            (archive / name).write_text(content)
        print("Rendered the dynamics checkpoint panel from archived runs.")
        return
    rows = [row for row in read_csv(args.analysis / "training_scalars.csv")
            if row["environment"] == "AntNavigate-v4" and row["variant"] in VARIANT_ORDER]
    curves = []
    assert len(rows) == 6
    provenance = []
    ant_protocol = None
    for row in rows:
        path = Path(row["run_dir"])
        config_path = path / "config.yaml"
        config_bytes = config_path.read_bytes()
        config = yaml.safe_load(config_bytes)
        tests = json_lines(path / "test.log")
        assert (path / "COMPLETE").is_file() and len(tests) == 1, path
        test = tests[0]
        assert test["succ_rate"] == float(row["test_success"]), path
        assert test["env_steps"] == int(row["selected_steps"]), path
        assert test["completed_training_env_steps"] == int(row["completed_steps"]), path
        assert config["env"]["name"] == row["environment"], path
        assert config["seed"] == int(row["seed"]), path
        assert config["agent"]["model_size"] == "GO-QRL-M", path
        dynamics = config["agent"]["quasimetric_critic"]["losses"]["latent_dynamics"]
        assert dynamics["distance"] == {"A01": "iqe", "A05": "iqe_mse"}[row["variant"]], path
        assert dynamics["weight"] == 0.1, path
        assert dynamics["iqe_weight"] == dynamics["mse_weight"] == 1, path
        for name in ("mse", "sq_dists"):
            assert math.isfinite(float(row[f"{name}_last10pct"])), path
            assert int(row[f"{name}_last_step"]) == int(row["completed_steps"]), path
        # Align both errors to the checkpoint that produced the reported test.
        events = load_scalar_events({
            "run_dir": str(path), "completed_steps": int(row["completed_steps"]),
        })
        for step in range(20000, int(row["completed_steps"]) + 1, 20000):
            window = {s for s in events["sq_dists"] if step - 20000 < s <= step}
            assert window == {s for s in events["mse"] if step - 20000 < s <= step}
            assert window
            curve = {key: row[key] for key in ("environment", "variant", "seed")}
            curve["env_steps"] = step
            for name, recorded in events.items():
                values = [event.value for s, event in sorted(recorded.items())
                          if step - 20000 < s <= step]
                curve[name] = statistics.mean(values) if values else ""
            curves.append(curve)
        selected_step = int(row["selected_steps"])
        iqe_steps = {step for step in events["sq_dists"]
                     if selected_step - 20000 < step <= selected_step}
        mse_steps = {step for step in events["mse"]
                     if selected_step - 20000 < step <= selected_step}
        assert iqe_steps == mse_steps and iqe_steps, path
        for name in ("mse", "sq_dists"):
            row[f"{name}_selected20k"] = statistics.mean(
                events[name][step].value for step in sorted(iqe_steps)
            )
        row["diagnostic_window_start_exclusive"] = selected_step - 20000
        row["diagnostic_window_end_inclusive"] = selected_step
        row["diagnostic_window_records"] = len(iqe_steps)
        actor = config["agent"]["actor"]["losses"]["min_dist"]
        row.update({
            "recorded_model_size": config["agent"]["model_size"],
            "recorded_completion_mode": actor["latent_goal_mode"],
            "recorded_completion_steps": actor["latent_goal_steps"],
            "recorded_completion_lr": actor["latent_goal_lr"],
        })
        assert (actor["latent_goal_mode"], actor["latent_goal_steps"], actor["latent_goal_lr"]) == (
            "max", 4, 0.01
        ), path
        if row["environment"] == "AntNavigate-v4":
            expected_runtime = "latent_goal_mode=max, latent_goal_steps=4, latent_goal_optim=sgd, latent_goal_lr=0.01"
            runtime = next(line.strip() for line in (path / "output.log").read_text().splitlines()
                           if "MinDistLoss(" in line)
            assert expected_runtime in runtime, path
            active = protocol(config)
            if ant_protocol is None:
                ant_protocol = active
            assert ant_protocol == active, path
            assert row["git_commit"] == "1612879794af6574d24f0214e1bd4959752ed87d", path
            provenance.append({
                "run_dir": str(path), "variant": row["variant"], "seed": config["seed"],
                "commit": row["git_commit"], "model_size": row["recorded_model_size"],
                "completion_mode": actor["latent_goal_mode"], "completion_steps": actor["latent_goal_steps"],
                "completion_lr": actor["latent_goal_lr"], "runtime_model_repr": runtime,
                "config_sha256": hashlib.sha256(config_bytes).hexdigest(),
                "test_sha256": hashlib.sha256((path / "test.log").read_bytes()).hexdigest(),
            })
    assert len(provenance) == 6 and len(curves) == 150
    data_root = PAPER_ROOT / "data"
    write_csv(data_root / "dynamics_mse_runs.csv", rows)
    write_csv(data_root / "dynamics_mse_ant_trajectories.csv", curves)
    write_csv(data_root / "dynamics_mse_summary.csv", summarize(rows))
    evidence_fields = (
        'environment', 'variant', 'seed', 'selected_steps', 'test_episodes',
        'test_success', 'mse_selected20k', 'sq_dists_selected20k',
        'diagnostic_window_start_exclusive', 'diagnostic_window_end_inclusive',
        'diagnostic_window_records',
    )
    write_csv(data_root / 'dynamics_mse_evidence.csv', [
        {key: row[key] for key in evidence_fields} for row in rows
    ])
    (data_root / "dynamics_mse_provenance.json").write_text(json.dumps({
        "role": "Small-parameter AntNavigate MSE comparison, not the final nearest-completion ablation",
        "scalar_window": "20k steps ending at each selected test checkpoint; identical IQE/MSE steps; latest wall-time record",
        "trajectory_window": "Preceding 20k environment steps, then mean across training seeds",
        "antnavigate_runs": provenance,
    }, indent=2) + "\n")
    for name, content in render_tables(rows, curves).items():
        (archive / name).write_text(content)
    print("Archived 1 former checkpoint panel, 6 run records, 150 trajectory windows, and 6 provenance records.")


if __name__ == "__main__":
    main()
